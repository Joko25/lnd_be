<?php
defined('BASEPATH') OR exit('No direct script access allowed');

class BasicCompetencyModel extends CI_Model {

    public function __construct() {
        parent::__construct();
    }

    public function get_all_data() {
        $query = $this->db->get('lnd_basic_competency');
        echo $query;
        return $query->result_array();
    }

    public function get_detail_data($id) {
        $query = $this->db->get_where('lnd_basic_competency', ['id' => $id]);

        if ($query->num_rows() > 0) {
            return $query->row_array(); 
        }

        return null;
    }

    public function insert_data($data) {
        $data['createdBy'] = $this->session->username;
        $data['createdTime'] = date('Y-m-d H:i:s');
        $this->db->insert('lnd_basic_competency', $data);

        $query = $this->db->order_by('createdTime', 'basicCompetenceId')->limit(1)->get('lnd_basic_competency');
    
        $record = $query->row();
    
        return $record; 
    }

    public function update_data($id, $data) {
        $this->db->where('id', $id);
        $data['updatedBy'] = $this->session->username;
        $data['updatedTime'] = date('Y-m-d H:i:s');

        $this->db->update('lnd_basic_competency', $data);
        
        $query = $this->db->order_by('updatedTime', 'basicCompetenceId')->limit(1)->get('lnd_basic_competency');
    
        $record = $query->row();
    
        return $record; 
    }

    public function delete_data($id) {
        $this->db->where('id', $id);
        $this->db->delete('lnd_basic_competency');
    }
}